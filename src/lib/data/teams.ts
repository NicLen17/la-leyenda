export function getTeamById(id: string): Team | undefined {
  return TEAMS.find((team) => team.id === id);
}

export function getTeamsByTier(tier: Tier, region?: Region): Team[] {
  return TEAMS.filter(
    (team) => team.tier === tier && (!region || team.region === region),
  );
}

export function getStarterTeam(region: Region): Team {
  const pool = getTeamsByTier(3, region);
  const fallback = TEAMS.filter((team) => team.tier === 3);
  const source = pool.length > 0 ? pool : fallback;
  return source[Math.floor(Math.random() * source.length)];
}
